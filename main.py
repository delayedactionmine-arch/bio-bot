def send_next_question(chat_id, uid):
    state = user_state.get(uid)
    if not state:
        return

    section_key = state["section"]
    section_title, questions = None, None
    for k, title, q in SECTIONS:
        if k == section_key:
            section_title, questions = title, q
            break

    if questions is None:  # «Все вперемешку» — соберём все вопросы
        questions = []
        for _, _, q in SECTIONS:
            if q:
                questions.extend(q)
        # Сохраним в state, чтобы индексы не «плыли»
        state["all_questions"] = questions

    asked = get_asked(uid, section_key)
    total = len(questions)

    # Ищем следующий непройденный вопрос
    while state["current_index"] < total and state["current_index"] in asked:
        state["current_index"] += 1

    if state["current_index"] >= total:
        # Все пройдены
        text = (
            f"🎉 *Поздравляю!*\n\n"
            f"Вы прошли все *{total}* вопросов раздела «{section_title}».\n\n"
            f"Хотите пройти его заново (уже без повторов) или выбрать другой раздел?"
        )
        bot.send_message(chat_id, text, parse_mode="Markdown",
                         reply_markup=end_keyboard(section_key))
        user_state.pop(uid, None)
        return

    idx = state["current_index"]
    question, correct, explanation = questions[idx]

    header = f"*Вопрос {idx + 1} из {total}*"
    if asked:
        header += f"  (пройдено: {len(asked)})"
    header += "\n"

    bot.send_message(
        chat_id,
        f"{header}\n{question}",
        parse_mode="Markdown",
        reply_markup=question_keyboard(),
    )


