@bot.callback_query_handler(func=lambda c: c.data.startswith("sec_"))
def cb_choose_section(call):
    key = call.data.replace("sec_", "")
    uid = call.message.chat.id

    section_title, questions = None, None
    for k, title, q in SECTIONS:
        if k == key:
            section_title, questions = title, q
            break

    if section_title is None:
        bot.answer_callback_query(call.id, "Раздел не найден")
        return

    if questions is None:  # «Все вперемешку»
        all_q = []
        for _, _, q in SECTIONS:
            if q:
                all_q.extend(q)
        # Перемешаем и запомним порядок в state
        order = list(range(len(all_q)))
        random.shuffle(order)
        questions = [all_q[i] for i in order]

    user_state[uid] = {
        "section": key,
        "current_index": 0,
        "score": 0,
        "questions": questions,
    }

    bot.answer_callback_query(call.id, f"Раздел: {section_title}")
    try:
        bot.delete_message(call.message.chat.id, call.message.message_id)
    except Exception:
        pass
    send_next_question(uid, uid)


@bot.callback_query_handler(func=lambda c: c.data.startswith("ans_"))
def cb_answer(call):
    uid = call.message.chat.id
    state = user_state.get(uid)
    if not state:
        bot.answer_callback_query(call.id, "Сессия устарела. /start")
        return

    user_answer = call.data == "ans_1"
    idx = state["current_index"]
    questions = state["questions"]
    question, correct, explanation = questions[idx]

    if user_answer == correct:
        result_line = "✅ *Правильно!*"
        state["score"] += 1
    else:
        right = "Да" if correct else "Нет"
        result_line = f"❌ *Ошибка!* Правильный ответ: *{right}*"

    text = f"{result_line}\n\n_Вопрос был:_ {question}\n\n💡 {explanation}"
    bot.edit_message_text(
        text,
        chat_id=uid,
        message_id=call.message.message_id,
        parse_mode="Markdown",
    )

    # Запоминаем, что вопрос пройден
    add_asked(uid, state["section"], idx)

    # Идём к следующему
    state["current_index"] += 1
    send_next_question(uid, uid)


