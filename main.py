user_state = {}   # {user_id: {"section": "...", "current_index": N, "score": 0, "asked": [..]}}


def user_progress(uid):
    """Возвращает dict с прогрессом пользователя."""
    uid_str = str(uid)
    if uid_str not in progress:
        progress[uid_str] = {}
    return progress[uid_str]


def get_asked(uid, section_key):
    """Список индексов вопросов, которые пользователь уже решил в этом разделе."""
    return user_progress(uid).get(section_key, [])


def add_asked(uid, section_key, idx):
    """Добавить индекс вопроса в пройденные."""
    up = user_progress(uid)
    lst = up.get(section_key, [])
    if idx not in lst:
        lst.append(idx)
    up[section_key] = lst
    save_progress(progress)


def reset_section(uid, section_key):
    up = user_progress(uid)
    up[section_key] = []
    save_progress(progress)


def reset_all(uid):
    progress[str(uid)] = {}
    save_progress(progress)


